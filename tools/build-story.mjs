// Validates the story graph and generates story.md from the node files.
// Run from the project root:  node tools/build-story.mjs
// (needs "type": "module" in package.json, or a recent Node that detects ESM)
import { writeFileSync } from 'node:fs'
import { introNodes } from '../story/intro.js'
import { phoneNodes } from '../story/phone.js'
import { investigateNodes } from '../story/investigate.js'
import { elfChatNodes } from '../story/elf/elf-chat.js'
import { elfFightNodes } from '../story/elf/elf-fight.js'
import { workshopEntranceNodes } from '../story/workshop/workshop-entrance.js'
import { workshopFloorNodes } from '../story/workshop/workshop-floor.js'
import { workshopOfficeNodes } from '../story/workshop/workshop-office.js'
import { mrsClausNodes } from '../story/workshop/mrs-claus.js'
import { noelNodes } from '../story/workshop/noel.js'
import { jackFrostNodes } from '../story/workshop/jack-frost.js'
import { workshopEndingNodes } from '../story/workshop/workshop-endings.js'
import { stablesYardNodes } from '../story/stables/stables-yard.js'
import { reindeerHandlerNodes } from '../story/stables/reindeer-handlers.js'
import { stablesLoftNodes } from '../story/stables/stables-loft.js'
import { stablesEndingNodes } from '../story/stables/stables-endings.js'

const START = 'intro-prologue'
const INITIAL_STATE = ['cigarettes', 'phone'] // flags that start as true

const sections = [
  ['Intro', introNodes],
  ['Phone', phoneNodes],
  ['Investigate', investigateNodes],
  ['Elf village: chat', elfChatNodes],
  ['Elf village: fight', elfFightNodes],
  ['Workshop: entrance', workshopEntranceNodes],
  ['Workshop: toy floor', workshopFloorNodes],
  ['Workshop: Santa\'s office', workshopOfficeNodes],
  ['Workshop: Mrs Claus', mrsClausNodes],
  ['Workshop: Noel', noelNodes],
  ['Workshop: Jack Frost', jackFrostNodes],
  ['Workshop: endings', workshopEndingNodes],
  ['Stables: yard', stablesYardNodes],
  ['Stables: reindeer handlers', reindeerHandlerNodes],
  ['Stables: hayloft', stablesLoftNodes],
  ['Stables: endings', stablesEndingNodes],
]

const all = sections.flatMap(([, nodes]) => nodes)
const byId = new Map()
const problems = []

for (const n of all) {
  if (byId.has(n.id)) problems.push(`DUPLICATE id: ${n.id}`)
  byId.set(n.id, n)
}

const reqText = (fn) =>
  fn.toString().split('=>').slice(1).join('=>').trim().replace(/currentState\./g, '')

const setBy = new Map()
const usedBy = new Map()
const add = (map, k, id) => map.set(k, [...(map.get(k) ?? []), id])

for (const n of all) {
  for (const o of n.options) {
    if (typeof o.nextText === 'number') {
      if (o.nextText > 0) problems.push(`${n.id}: numeric nextText ${o.nextText}`)
    } else if (!byId.has(o.nextText)) {
      problems.push(`DANGLING link: ${n.id} -> ${o.nextText}`)
    }
    if (/\.$/.test(o.text)) problems.push(`${n.id}: option ends with full stop: "${o.text}"`)
    if (o.setState) for (const k of Object.keys(o.setState)) add(setBy, k, n.id)
    if (o.requiredState) {
      for (const m of reqText(o.requiredState).matchAll(/[A-Za-z_]+/g)) add(usedBy, m[0], n.id)
    }
  }
}

// reachability (ignores state gating, so it shows the structural maximum)
const seen = new Set([START])
const queue = [START]
while (queue.length) {
  const n = byId.get(queue.shift())
  for (const o of n?.options ?? []) {
    if (typeof o.nextText === 'string' && !seen.has(o.nextText)) {
      seen.add(o.nextText)
      queue.push(o.nextText)
    }
  }
}
for (const id of byId.keys()) if (!seen.has(id)) problems.push(`UNREACHABLE: ${id}`)

// dead ends that are not endings
for (const n of all) {
  if (n.options.length === 0) problems.push(`DEAD END (no options): ${n.id}`)
}

// state flags
for (const k of usedBy.keys()) {
  if (!setBy.has(k) && !INITIAL_STATE.includes(k)) problems.push(`FLAG never set: ${k}`)
}
const unusedFlags = [...setBy.keys()].filter((k) => !usedBy.has(k))

// ---- markdown ----
const italicSpeech = (t) => t.replace(/"([^"]+)"/g, '*"$1"*')
const note = (o) => {
  const bits = []
  if (o.requiredState) bits.push(`requires: ${reqText(o.requiredState)}`)
  if (o.setState) bits.push(`sets: ${Object.entries(o.setState).map(([k, v]) => `${k} = ${v}`).join(', ')}`)
  return bits.length ? ` *(${bits.join(' · ')})*` : ''
}

let md = `Credit to WebDevSimplified - forked from https://github.com/WebDevSimplified/JavaScript-Text-Adventure

<!-- Generated by tools/build-story.mjs. Edit the .js files, then re-run. -->

# Story

**Endings:** [The Vice Head Elf](#ending-the-vice-head-elf) · [Hostile Takeover](#ending-hostile-takeover) · [Early Retirement](#ending-early-retirement) · [Cold Case](#ending-cold-case)

`

for (const [title, nodes] of sections) {
  md += `## ${title}\n\n`
  for (const n of nodes) {
    md += `### ${n.id}\n\n${italicSpeech(n.text)}\n\n`
    for (const o of n.options) {
      const target = typeof o.nextText === 'number' ? START : o.nextText
      md += `- [${o.text}](#${target})${note(o)}\n`
    }
    if (n.options.length) md += '\n'
  }
}

md += `## State reference\n\n`
for (const k of [...new Set([...setBy.keys(), ...INITIAL_STATE])].sort()) {
  const s = INITIAL_STATE.includes(k) ? ['(starts true)', ...(setBy.get(k) ?? [])] : setBy.get(k)
  md += `- **${k}** — set: ${[...new Set(s)].join(', ')}; used: ${[...new Set(usedBy.get(k) ?? ['-'])].join(', ')}\n`
}

writeFileSync(new URL('../story/story.md', import.meta.url), md)

console.log(`nodes: ${all.length}, reachable: ${seen.size}`)
console.log(`endings: ${all.filter((n) => n.id.startsWith('ending-')).length}`)
console.log(problems.length ? 'PROBLEMS:\n' + problems.join('\n') : 'No problems found')
if (unusedFlags.length) console.log('flags set but never required (fine if just flavour):', unusedFlags.join(', '))